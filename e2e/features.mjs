import { chromium } from "@playwright/test";
const S = process.env.SHOTS || ".";
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:4173/#/");
console.log("default theme:", await page.evaluate(() => document.documentElement.dataset.theme));
await page.click("text=Crea la prima lavagna");
await page.waitForSelector(".excalidraw");
await page.mouse.click(640, 500);
// rettangolo + freccia che parte dalla metà del lato destro (snap attivo di default)
await page.keyboard.press("r");
await page.mouse.move(300, 300); await page.mouse.down(); await page.mouse.move(500, 440, { steps: 6 }); await page.mouse.up();
await page.keyboard.press("Escape");
console.log("snap enabled:", await page.evaluate(() => !!document.querySelector(".excalidraw")));
await page.keyboard.press("a");
await page.mouse.move(503, 372); await page.mouse.down(); await page.mouse.move(760, 372, { steps: 10 });
await page.screenshot({ path: `${S}/20-snap-while-drawing.png` });
await page.mouse.up();
await page.keyboard.press("Escape");
// foglio a quadretti
await page.click('[aria-label="Foglio"]');
await page.click("text=Quadretti");
await page.waitForTimeout(300);
await page.screenshot({ path: `${S}/21-paper-squares.png` });
await page.click('[aria-label="Foglio"]');
await page.click("text=Righe");
await page.click('[aria-label="Foglio"]');
await page.click("text=Grandi");
await page.waitForTimeout(300);
await page.screenshot({ path: `${S}/22-paper-lines-large.png` });
// colori preferiti: seleziona rettangolo, apri pannello, scegli colore via hex
await page.keyboard.press("Escape");
await page.mouse.click(300, 370);
await page.click('[aria-label="Colori preferiti"]');
await page.waitForSelector(".colorfav-pop");
await page.fill(".colorfav-hex input", "#e8590c");
await page.keyboard.press("Enter");
await page.click("button:has-text(\"Salva nei preferiti\")");
await page.click(".colorfav-pop button:has-text(\"Sfondo\")");
await page.fill(".colorfav-hex input", "#ffe8cc");
await page.keyboard.press("Enter");
await page.click("button:has-text(\"Salva nei preferiti\")");
await page.waitForTimeout(300);
await page.screenshot({ path: `${S}/23-colors.png` });
console.log("favorites:", await page.$$eval(".swatch-wrap .swatch", (xs) => xs.map((x) => x.title)));
// puntini in tema scuro
await page.keyboard.press("Escape");
await page.click('[aria-label="Foglio"]');
await page.click("text=Puntini");
await page.click('[aria-label="Torna alle lavagne"]');
await page.waitForSelector(".card");
await page.click('[aria-label="Tema"]'); await page.click("text=Scuro");
await page.click(".card");
await page.waitForSelector(".excalidraw");
await page.waitForTimeout(600);
await page.screenshot({ path: `${S}/24-dots-dark.png` });
console.log("ERRORS:", errors.length ? errors : "none");
await browser.close();
