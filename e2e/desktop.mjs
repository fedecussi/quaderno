import { _electron as electron } from "@playwright/test";
const S = process.env.SHOTS || ".";
const app = await electron.launch({ args: [".", "--no-sandbox"], env: { ...process.env, ELECTRON_DISABLE_SECURITY_WARNINGS: "1" } });
const win = await app.firstWindow();
const errors = [];
win.on("pageerror", (e) => errors.push(e.message));
win.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await win.waitForSelector(".empty-hero, .card", { timeout: 20000 });
console.log("url:", win.url(), "title:", await win.title());
if (await win.$(".card")) await win.click("button:has-text(\"Nuova lavagna\")"); else await win.click("text=Crea la prima lavagna");
await win.waitForSelector(".excalidraw");
await win.keyboard.press("r");
await win.mouse.move(400, 300); await win.mouse.down(); await win.mouse.move(600, 420, { steps: 6 }); await win.mouse.up();
await win.waitForTimeout(3500);
console.log("save:", await win.textContent(".save-indicator"), "| Excalifont:", await win.evaluate(() => document.fonts.check('16px "Excalifont"')));
await win.screenshot({ path: `${S}/70-electron.png` });
await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].loadURL("app://quaderno/index.html#/new"));
await win.waitForSelector(".excalidraw", { timeout: 15000 });
await win.waitForTimeout(500);
console.log("#/new →", win.url());
console.log("ERRORS:", errors.length ? errors : "none");
await app.close();
